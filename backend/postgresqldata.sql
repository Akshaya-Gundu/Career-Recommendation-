 CREATE TABLE IF NOT EXISTS students (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL, email TEXT, education TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS student_skills (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      skill_name TEXT NOT NULL, proficiency INTEGER NOT NULL DEFAULT 1
    );
    CREATE TABLE IF NOT EXISTS student_interests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      interest TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS student_projects (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      title TEXT NOT NULL, description TEXT
    );
    CREATE TABLE IF NOT EXISTS careers (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT UNIQUE NOT NULL, description TEXT
    );
    CREATE TABLE IF NOT EXISTS career_skills (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      career_id BIGINT NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
      skill_name TEXT NOT NULL, weight INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS career_interests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      career_id BIGINT NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
      interest TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS learning_progress (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      career_id BIGINT NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
      skill_name TEXT NOT NULL, severity TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'not_started', progress_percent INTEGER NOT NULL DEFAULT 0,
      updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      UNIQUE(student_id, career_id, skill_name)
    );