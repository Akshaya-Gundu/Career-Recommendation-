require("dotenv").config({ path: require("path").join(__dirname, ".env") });

const { Pool } = require("pg");
const careers = require("./data/careers");

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  // Serverless instances are short lived; keep each instance's connection use small.
  max: Number(process.env.PG_POOL_MAX) || 3,
  ssl: process.env.DATABASE_URL && process.env.NODE_ENV === "production"
    ? { rejectUnauthorized: false }
    : undefined
});

async function initializeDatabase() {
  if (!process.env.DATABASE_URL) {
    throw new Error("DATABASE_URL is missing. Copy backend/.env.example to backend/.env and set your PostgreSQL connection string.");
  }
  let databaseUrl;
  try {
    databaseUrl = new URL(process.env.DATABASE_URL);
  } catch {
    throw new Error("DATABASE_URL is not a valid PostgreSQL URL. Use postgresql://USER:PASSWORD@HOST:5432/DATABASE.");
  }
  const connectionParts = [databaseUrl.hostname, databaseUrl.username, databaseUrl.password, databaseUrl.pathname];
  if (connectionParts.some((part) => /your[-_ ]?(host|user(name)?|password|database)|placeholder|\.\.\.|<[^>]+>/i.test(decodeURIComponent(part)))) {
    throw new Error("DATABASE_URL still contains example values. Replace the username, password, host, and database with the values from your PostgreSQL provider.");
  }
  if (!["postgres:", "postgresql:"].includes(databaseUrl.protocol)) {
    throw new Error("DATABASE_URL must use the postgresql:// or postgres:// protocol.");
  }
  await pool.query(`
    CREATE TABLE IF NOT EXISTS students (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL, email TEXT, education TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS student_skills (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      skill_name TEXT NOT NULL, proficiency INTEGER NOT NULL DEFAULT 1
    );
    CREATE TABLE IF NOT EXISTS student_interests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      interest TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS student_projects (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      title TEXT NOT NULL, description TEXT
    );
    CREATE TABLE IF NOT EXISTS careers (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT UNIQUE NOT NULL, description TEXT
    );
    CREATE TABLE IF NOT EXISTS career_skills (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      career_id BIGINT NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
      skill_name TEXT NOT NULL, weight INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS career_interests (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      career_id BIGINT NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
      interest TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS learning_progress (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      career_id BIGINT NOT NULL REFERENCES careers(id) ON DELETE CASCADE,
      skill_name TEXT NOT NULL, severity TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'not_started', progress_percent INTEGER NOT NULL DEFAULT 0,
      updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      UNIQUE(student_id, career_id, skill_name)
    );
  `);

  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    // Prevent simultaneous Vercel cold starts from trying to seed the same rows.
    await client.query("SELECT pg_advisory_xact_lock($1)", [748231904]);
    const { rows } = await client.query("SELECT COUNT(*)::int AS count FROM careers");
    if (rows[0].count) {
      await client.query("COMMIT");
      return;
    }
    for (const career of careers) {
      const inserted = await client.query(
        "INSERT INTO careers (name, description) VALUES ($1, $2) RETURNING id",
        [career.name, career.description]
      );
      const careerId = inserted.rows[0].id;
      for (const [skill, weight] of Object.entries(career.skills)) {
        await client.query(
          "INSERT INTO career_skills (career_id, skill_name, weight) VALUES ($1, $2, $3)",
          [careerId, skill, weight]
        );
      }
      for (const interest of career.interests) {
        await client.query("INSERT INTO career_interests (career_id, interest) VALUES ($1, $2)", [careerId, interest]);
      }
    }
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

module.exports = { query: (...args) => pool.query(...args), pool, initializeDatabase };
